namespace AjamaGhouligan.AjamaGhouliganCode.Cards.Multiplayer;

public class BakersHand() : AjamaGhouliganCard(1,
    CardType.Power, CardRarity.Uncommon,
    TargetType.Self)
{
    public override CardMultiplayerConstraint MultiplayerConstraint => CardMultiplayerConstraint.MultiplayerOnly;
    
    protected override IEnumerable<DynamicVar> CanonicalVars =>
    [
        new PowerVar<BakersHandPower>(1)
    ];

    public override BundledHoverTipManager MyBundles =>
    [
        new PattyCakeBundle(2),
        BundledHoverTipFactory.FromPower<VigorPower>()
    ];

    protected override async Task OnPlay(
        PlayerChoiceContext choiceContext,
        CardPlay play)
    {
        await CreatureCmd.TriggerAnim(Owner.Creature, "PowerUp", Owner.Character.PowerUpAnimDelay);

        await CommonActions.ApplySelf<BakersHandPower>(choiceContext, this);
    }

    protected override void OnUpgrade()
    {
        AddKeyword(CardKeyword.Innate);
    }
}